isr_common_stub:
    /* Simpan semua register ke stack (trap frame) */
    pushq %rax
    pushq %rcx
    pushq %rdx
    pushq %rbx
    pushq %rbp
    pushq %rsi
    pushq %rdi
    pushq %r8
    pushq %r9
    pushq %r10
    pushq %r11
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15

    /* RSP sekarang = pointer ke trap_frame_t */
    /* Simpan ke RBX (callee-saved, tidak diubah oleh C) */
    movq  %rsp, %rbx

    /* Align stack ke 16 byte untuk ABI */
    movq  %rsp, %rdi      /* argumen pertama = pointer trap frame */
    andq  $-16, %rsp
    call  x86_64_trap_dispatch

    /* Restore RSP ke trap frame dari RBX */
    movq  %rbx, %rsp

    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %r11
    popq %r10
    popq %r9
    popq %r8
    popq %rdi
    popq %rsi
    popq %rbp
    popq %rbx
    popq %rdx
    popq %rcx
    popq %rax

    addq $16, %rsp    /* buang vector + error_code */
    iretq

